const COUNTRY_BY_ALPHA2 = new Map(ISO_COUNTRIES.map(country => [country.alpha2, country]));

export function getIsoCountry(code: string | null | undefined): IsoCountryReference | null {
  return COUNTRY_BY_ALPHA2.get(String(code ?? '').trim().toUpperCase()) ?? null;
}

export function getIsoCountryName(code: string | null | undefined, language: CountryLanguage = 'en'): string | null {
  const country = getIsoCountry(code);
  return country ? (language === 'he' ? country.nameHe : country.nameEn) : null;
}

/** Keep both names visible so EN and HE users can identify the same code. */
export function isoCountryOptionLabel(country: IsoCountryReference, language: CountryLanguage = 'en'): string {
  const primary = language === 'he' ? country.nameHe : country.nameEn;
  const secondary = language === 'he' ? country.nameEn : country.nameHe;
  return `${country.alpha2} — ${primary} / ${secondary}`;
}
