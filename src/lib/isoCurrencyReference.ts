const CURRENCY_BY_CODE = new Map(ISO_CURRENCY_REFERENCE.map(currency => [currency.code, currency]));

export function getIsoCurrency(code: string | null | undefined): IsoCurrencyReference | null {
  return CURRENCY_BY_CODE.get(String(code ?? '').trim().toUpperCase()) ?? null;
}

/** Search by alphabetic code, official currency name or the stored display symbol. */
export function searchIsoCurrencyReference(query: string | null | undefined): IsoCurrencyReference[] {
  const needle = String(query ?? '').trim().toLowerCase();
  if (!needle) return [...ISO_CURRENCY_REFERENCE];
  return ISO_CURRENCY_REFERENCE.filter(currency =>
    currency.code.toLowerCase().includes(needle) ||
    currency.name.toLowerCase().includes(needle) ||
    (currency.symbol ?? '').toLowerCase().includes(needle),
  );
}
