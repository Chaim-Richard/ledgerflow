import './helpers/dom';
import test, {afterEach} from 'node:test';
import assert from 'node:assert/strict';
import React from 'react';
import {act, cleanup, render, screen} from '@testing-library/react';
import {moneyText} from '../lib/moneyFormat';
import {currencyChartValue, formatCurrency} from '../lib/utils';
import Money from '../components/ui/Money';
import {useAuthStore} from '../stores/useAuthStore';
import {setComponentWorkspace} from './helpers/componentFixtures';
import {getSupabase} from '../lib/db/client';
afterEach(async()=>{cleanup(); useAuthStore.setState({workspaces:[],currentWorkspaceId:null}); window.__ledgerBaseCurrency='USD'; await getSupabase().auth.dispose();});
test('locale currency placement, separators and accounting negatives preserve minor units',()=>{
 assert.equal(moneyText(123456,'USD',2,{locale:'en-US'}),'$1,234.56');
 assert.equal(moneyText(123456,'EUR',2,{locale:'de-DE'}),'1.234,56 €');
 assert.equal(moneyText(-123456,'USD',2,{locale:'en-US',negativeStyle:'accounting'}),'($1,234.56)');
 assert.equal(moneyText(-123456,'EUR',2,{locale:'de-DE',negativeStyle:'accounting'}),'(1.234,56 €)');
 assert.equal(moneyText(1234,'JPY',0,{locale:'ja-JP'}),'￥1,234');
 assert.equal(moneyText(123456,'KWD',3,{locale:'en-US'}),'KWD 123.456');
 assert.equal(moneyText(null,'USD',2,{locale:'en-US'}),'$0.00');
 assert.equal(moneyText(Infinity,'USD',2,{locale:'en-US'}),'$0.00');
 assert.equal(moneyText(1234,'invalid',2,{locale:'en-US'}),'invalid 12.34');
 assert.equal(moneyText(1234,'USD',2,{locale:'not_a_locale'}),moneyText(1234,'USD',2));
 assert.equal(moneyText(1234,'USD',2),new Intl.NumberFormat(undefined,{style:'currency',currency:'USD'}).format(12.34));
});
test('Hebrew money retains native RTL marks; accounting negatives and isolated Money rerender on workspace changes',()=>{
 const text=moneyText(123456,'ILS',2,{locale:'he-IL'});
 assert.match(text,/1,234\.56/);assert.ok(text.includes('₪'));
 assert.equal(moneyText(-123456,'ILS',2,{locale:'he-IL',negativeStyle:'accounting'}),`(${text})`);
 const workspace=setComponentWorkspace();
 const formatted={...workspace,moneyDisplay:{locale:'de-DE',negativeStyle:'accounting'}};
 act(()=>useAuthStore.setState({workspaces:[formatted]}));
 assert.equal(formatCurrency(-123456,'EUR'),'(1.234,56 €)');
 render(<div dir="rtl">סכום <Money cents={-123456} currency="EUR" /></div>);
 const span=screen.getByText(/\(1\.234,56\s€\)/);assert.equal(span.getAttribute('dir'),'auto');assert.equal(span.style.unicodeBidi,'isolate');
 const american={...workspace,moneyDisplay:{locale:'en-US'}};
 act(()=>useAuthStore.setState({workspaces:[american]}));
 assert.ok(screen.getByText('-€1,234.56'));
 window.__ledgerBaseCurrency='JPY'; assert.equal(currencyChartValue(1234),1234);
 window.__ledgerBaseCurrency='KWD'; assert.equal(currencyChartValue(123456),123.456);
});
